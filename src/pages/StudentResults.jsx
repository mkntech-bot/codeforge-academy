
import { useEffect, useState } from "react";
import { useNavigate } from "react-router-dom";
import { supabase } from "../lib/supabase";
import jsPDF from "jspdf";

function StudentResults() {
  const navigate = useNavigate();

  const [student, setStudent] = useState(null);
  const [results, setResults] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

function downloadResultPDF(result) {
  const doc = new jsPDF();

  const score = Number(result.final_score ?? 0);
  const total = Number(result.total_marks ?? 0);
  const automaticMarks = Number(result.auto_marks ?? 0);
  const instructorMarks = Math.max(0, score - automaticMarks);

  const percentage =
    total > 0 ? ((score / total) * 100).toFixed(1) : "0.0";

  // PDF HEADER
  doc.setFillColor(49, 103, 232);
  doc.rect(0, 0, 210, 42, "F");

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.setFont("helvetica", "bold");
  doc.text("CodeForge Academy", 15, 19);

  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.text("Student Assignment Result Report", 15, 29);

  // STUDENT INFORMATION
  let y = 58;

  doc.setTextColor(23, 37, 84);
  doc.setFontSize(14);
  doc.setFont("helvetica", "bold");
  doc.text("STUDENT INFORMATION", 15, y);

  y += 12;

  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");

  doc.text(`Student Name: ${student?.full_name || "N/A"}`, 15, y);
  y += 8;

  doc.text(`Student Code: ${student?.student_code || "N/A"}`, 15, y);
  y += 8;

  doc.text(`Class: ${student?.class_group || "N/A"}`, 15, y);

  // ASSIGNMENT INFORMATION
  y += 17;

  doc.setFontSize(14);
  doc.setFont("helvetica", "bold");
  doc.text("ASSIGNMENT INFORMATION", 15, y);

  y += 12;

  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");

  const titleLines = doc.splitTextToSize(
    `Assignment: ${result.assignment_title || "Assignment"}`,
    180
  );

  doc.text(titleLines, 15, y);
  y += titleLines.length * 7;

  doc.text(`Submitted: ${formatDate(result.submitted_at)}`, 15, y);
  y += 8;

  doc.text(`Published: ${formatDate(result.published_at)}`, 15, y);

  // SCORE SUMMARY
  y += 17;

  doc.setFillColor(240, 244, 250);
  doc.roundedRect(15, y - 7, 180, 40, 3, 3, "F");

  doc.setTextColor(49, 103, 232);
  doc.setFontSize(19);
  doc.setFont("helvetica", "bold");
  doc.text(`FINAL SCORE: ${score} / ${total}`, 23, y + 7);

  doc.setTextColor(100, 116, 139);
  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.text(`Performance: ${percentage}%`, 23, y + 21);

  y += 52;

  // MARKS BREAKDOWN
  doc.setTextColor(23, 37, 84);
  doc.setFontSize(14);
  doc.setFont("helvetica", "bold");
  doc.text("MARKS BREAKDOWN", 15, y);

  y += 12;

  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(71, 85, 105);

  doc.text(`Automatic Marks: ${automaticMarks}`, 15, y);
  y += 9;

  doc.text(`Instructor-awarded Marks: ${instructorMarks}`, 15, y);
  y += 9;

  doc.setFont("helvetica", "bold");
  doc.text(`Total Score: ${score} / ${total}`, 15, y);

  // INSTRUCTOR FEEDBACK
  y += 18;

  doc.setFontSize(14);
  doc.setTextColor(23, 37, 84);
  doc.text("INSTRUCTOR FEEDBACK", 15, y);

  y += 9;

  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(100, 116, 139);

  const feedback = result.instructor_feedback?.trim()
    || "No feedback was provided.";

  const feedbackLines = doc.splitTextToSize(feedback, 175);

  if (y + feedbackLines.length * 7 > 275) {
    doc.addPage();
    y = 25;
  }

  doc.text(feedbackLines, 15, y);

  // FOOTER
  doc.setFontSize(9);
  doc.setTextColor(130, 144, 165);
  doc.text(
    "Generated by CodeForge Academy Student Portal",
    105,
    285,
    { align: "center" }
  );

  const filename = `CodeForge-Result-${student?.student_code || "Student"}.pdf`;

  doc.save(filename);
}


  useEffect(() => {
    let active = true;

    async function loadResults() {
      const token = sessionStorage.getItem("codeforge_student_token");

      if (!token) {
        navigate("/student-assignments", { replace: true });
        return;
      }

      try {
        const { data, error: requestError } =
          await supabase.functions.invoke("student-results", {
            method: "POST",
            headers: {
              "x-student-token": token,
            },
          });

        if (requestError) throw requestError;

        if (!data?.success) {
          if (active) {
            setError(data?.error || "Could not load your results.");
          }
          return;
        }

        if (active) {
          setStudent(data.student);
          setResults(data.results || []);
        }
      } catch (err) {
        console.error("Results loading error:", err);

        if (active) {
          setError(
            err.message || "Something went wrong. Please try again."
          );
        }
      } finally {
        if (active) setLoading(false);
      }
    }

    loadResults();

    return () => {
      active = false;
    };
  }, [navigate]);

  function formatDate(date) {
    if (!date) return "Not available";

    return new Date(date).toLocaleDateString("en-GB", {
      day: "numeric",
      month: "long",
      year: "numeric",
    });
  }

  if (loading) {
    return (
      <div className="student-results-page">
        <div className="results-loading">
          Loading your results...
        </div>
      </div>
    );
  }

  return (
    <div className="student-results-page">
      <header className="results-header">
        <div>
          <h2>CodeForge Academy</h2>
          <p>Student Results Portal</p>
        </div>

        <button
          type="button"
          onClick={() => navigate("/student")}
        >
          Back to Dashboard
        </button>
      </header>

      <main className="results-container">
        {student && (
          <section className="results-welcome">
            <p className="results-welcome-label">WELCOME BACK</p>

            <h1>{student.full_name}</h1>

            <div className="results-student-info">
              <span>
                Student Code: {student.student_code}
              </span>

              <span>
                Class: {student.class_group}
              </span>
            </div>
          </section>
        )}

        <section className="results-section">
          <h2>My Assignment Results</h2>

          <p className="results-description">
            View your published assignment scores and instructor feedback.
          </p>

          {error && (
            <div className="results-error">
              {error}
            </div>
          )}

          {!error && results.length === 0 && (
            <div className="results-empty">
              <h3>No published results yet</h3>

              <p>
                Your results will appear here once your instructor
                publishes them.
              </p>
            </div>
          )}

          <div className="results-list">
            {results.map((result) => {
              const score = Number(result.final_score ?? 0);
              const total = Number(result.total_marks ?? 0);
              const automaticMarks = Number(result.auto_marks ?? 0);

              const instructorMarks = Math.max(
                0,
                score - automaticMarks
              );

              const percentage =
                total > 0
                  ? Math.min(
                      100,
                      Math.max(0, (score / total) * 100)
                    )
                  : 0;

              return (
                <article
                  className="result-card"
                  key={result.submission_id}
                >
                  <div className="result-card-top">
                    <div className="result-assignment-info">
                      <h3>{result.assignment_title}</h3>

                      <p>
                        Published: {formatDate(result.published_at)}
                      </p>
                    </div>

                    <span className="result-published">
                      Published
                    </span>
                  </div>

                  <div className="result-score">
                    <strong>
                      {score} / {total}
                    </strong>

                    <span>Final Score</span>
                  </div>

                  <div className="result-progress">
                    <div
                      className="result-progress-fill"
                      style={{ width: `${percentage}%` }}
                    />
                  </div>

                  <div className="result-percentage">
                    {percentage.toFixed(1)}% achieved
                  </div>

                  <div className="result-breakdown">
                    <div>
                      <span>Automatic marks</span>
                      <strong>{automaticMarks}</strong>
                    </div>

                    <div>
                      <span>Instructor-awarded marks</span>
                      <strong>{instructorMarks}</strong>
                    </div>

                    <div className="result-total-row">
                      <span>Total marks</span>
                      <strong>{score} / {total}</strong>
                    </div>
                  </div>

                  <div className="result-feedback">
                    <h4>Instructor Feedback</h4>

                    <p>
                      {result.instructor_feedback?.trim()
                        ? result.instructor_feedback
                        : "No feedback was provided for this assignment."}
                    </p>
                  </div>

                  <p className="result-submitted-date">
                    Submitted: {formatDate(result.submitted_at)}
                  </p>
                  <button
                    type="button"
                    className="result-download-button"
                    onClick={() => downloadResultPDF(result)}
                  >
                    Download Result PDF
                  </button>
                </article>
              );
            })}
          </div>
        </section>
      </main>
    </div>
  );
}

export default StudentResults;
